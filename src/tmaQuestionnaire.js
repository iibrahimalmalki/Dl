// تحويل إجابات الاستبيان (index->1..5) إلى درجات المحاور 1..9
export function scoreFromAnswers(ans){
  const by={};
  ITEMS.forEach((it,i)=>{
    const v=Number(ans&&ans[i]);
    if(!v)return;
    const towardA=it.pole==="a"?v:(6-v); // اعكس عبارات الطرف المنخفض
    (by[it.drive]=by[it.drive]||[]).push(towardA);
  });
  const scores={};
  Object.keys(by).forEach(k=>{
    const arr=by[k];const avg=arr.reduce((a,b)=>a+b,0)/arr.length; // 1..5
    scores[k]=Math.max(1,Math.min(9,Math.round(1+(avg-1)/4*8)));  // → 1..9
  });
  return scores;
}

